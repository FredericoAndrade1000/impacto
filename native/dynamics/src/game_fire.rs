    #[test]
    fn a_damaged_turbine_develops_a_finite_fire_without_burning_its_metal_or_remote_fuel() {
        let mut d=DamageState::default();
        d.insert_module(piece(1,7,"thruster",json!({"metal":"titanium"})));
        d.insert_module(piece(2,7,"fuel",json!({"x":15.0,"fuelLitres":80,"capacityLitres":80})));
        let original=d.module(1).unwrap().live_mass();
        let mut e=Effects::new(true);
        d.damage_module(1,60.0,point(1.0,1.0),&mut e);
        assert!(!d.module(1).unwrap().burning,"moderate damage does not ignite a turbine");
        d.damage_module(1,20.0,point(1.0,1.0),&mut e);
        assert!(d.module(1).unwrap().burning);
        step(&mut d,&Geometry::new(),0.1,&mut e);
        let first=e.events.iter().find(|e|e["type"]=="burn").unwrap()["strength"].as_f64().unwrap();
        assert!(first>0.0 && first<0.12);
        for _ in 0..240 {step(&mut d,&Geometry::new(),0.1,&mut e);}
        let developed=e.events.iter().rev().find(|e|e["type"]=="burn").unwrap()["strength"].as_f64().unwrap();
        assert!(developed>first*5.0);
        for _ in 0..1200 {step(&mut d,&Geometry::new(),0.1,&mut e);}
        let turbine=d.module(1).unwrap();
        assert!(!turbine.burning);
        assert!(turbine.live_mass()<original && turbine.live_mass()>original*0.9,"only combustible contents are lost");
        assert_eq!(d.module(2).unwrap().fuel_litres,80.0);
        assert_eq!(d.module(2).unwrap().health,100.0);
        assert!(e.detonations.is_empty());
    }

//! Local combustion and heat transfer, aggregated into one visual fire per interior.
use crate::game_damage::{DamageState, Effects, MaterialKind, Module, point};
use crate::game_geometry::{CARGO, ComponentKind, Geometry, RayHit, RayOptions};
use serde_json::json;
use std::collections::BTreeMap;

const SOLID_SECONDS: f64 = 90.0;
const LIQUID_SECONDS: f64 = 180.0;
const AMMO_SECONDS: f64 = 45.0;
const HEAT_PER_SECOND: f64 = 0.018;
const GROWTH_SECONDS: f64 = 24.0;
const EXTERIOR_REACH: f64 = 1.5;
const INTERIOR_REACH: f64 = 2.5;

// Effective thermal resistance, not ballistic resistance. A material chord
// attenuates heat instead of becoming perfect insulation. These reference
// depths are gameplay approximations; health still accumulates exposure before
// ignition, without another temperature/checkpoint state.
fn transmission(damage: &DamageState, barriers: &[RayHit]) -> f64 {
    barriers.iter().fold(1.0, |share, hit| {
        let material = damage.plate(hit.owner).map(|plate| plate.material.kind)
            .or_else(|| damage.module(hit.owner).map(|module| module.metal().material().kind))
            .unwrap_or(MaterialKind::Steel);
        let reference = match material {
            MaterialKind::Aluminum => 0.030,
            MaterialKind::Steel | MaterialKind::HardSteel => 0.012,
            MaterialKind::Titanium => 0.008,
            MaterialKind::Glass => 0.004,
            MaterialKind::Fiberglass | MaterialKind::Plastic => 0.003,
            MaterialKind::Ceramic | MaterialKind::Concrete => 0.002,
        };
        share / (1.0 + hit.depth.max(0.0) / reference)
    })
}

// Admission already knows which equipment is outside a closed room. Running gear
// is outside the hull even when its construction-box projection has no exposed flag.
pub fn exterior(module: &Module) -> bool {
    module.kind.gear() || module.cold["exposed"] == true
}
fn scope(module: &Module) -> (u32, Option<u32>) {
    (module.actor, exterior(module).then_some(module.owner))
}

// Each ignition develops before it can consume its own fuel at full rate.
// Game time is compressed; this is a growth/decay approximation, not a compartment solver.
pub fn development(age: f64) -> f64 {
    0.06 + 0.94 * (age / GROWTH_SECONDS).clamp(0.0, 1.0).powi(2)
}
pub fn involvement(age: f64) -> f64 {
    ((development(age) - 0.12) / 0.88).clamp(0.0, 1.0)
}

// Combustible interiors, oils, seals, rubber and resin, not the metal casing.
// Keep every kind explicit so a new component must choose what can burn. Fractions
// are gameplay approximations; consumed material is never regenerated by another fire.
pub fn solid_fuel(module: &Module) -> f64 {
    let share: f64 = match module.kind {
        ComponentKind::Engine | ComponentKind::Thruster => 0.04,
        ComponentKind::Wheel => 0.55,
        ComponentKind::Track => 0.05,
        ComponentKind::Sensor | ComponentKind::Command => 0.04,
        ComponentKind::Ammo => 0.02,
        ComponentKind::Excavator | ComponentKind::Drill | ComponentKind::Builder | ComponentKind::Blade | ComponentKind::Paver => 0.02,
        ComponentKind::Supply | ComponentKind::Weapon => 0.01,
        ComponentKind::Fuel | ComponentKind::Hopper | ComponentKind::Cistern => 0.0,
    };
    let share = match module.metal().name { "plastic" => share.max(0.8), "fiberglass" => share.max(0.2), _ => share };
    module.dry_mass * share
}
pub fn consumed_solid(module: &Module) -> f64 {
    if module.burn_age <= 0.0 { return 0.0; }
    solid_fuel(module) * (module.burn_age / SOLID_SECONDS).clamp(0.0, 1.0)
}
fn remaining(module: &Module) -> f64 {
    solid_fuel(module) * (1.0 - module.burn_age / SOLID_SECONDS).clamp(0.0, 1.0)
        + module.fuel_litres.max(0.0) * 0.835
        + module.cargo[3].max(0.0) * CARGO[3].unit_mass()
        + module.rounds as f64 * module.round_mass * 0.2
}
pub fn ignites(module: &Module) -> bool {
    if !module.attached || remaining(module) <= 1e-8 { return false; }
    match module.kind {
        ComponentKind::Fuel => module.fuel_litres > 0.0 && module.health < module.max_health * 0.65,
        ComponentKind::Engine | ComponentKind::Thruster => module.health < module.max_health * 0.25,
        ComponentKind::Ammo => module.health <= 0.0 && module.rounds > 0,
        kind if kind.carrier() => module.cargo[3] > 0.0 && module.health < module.max_health * 0.45,
        _ => false,
    }
}
pub fn extinguish(damage: &mut DamageState, actor: u32) {
    for module in &mut damage.modules {
        if module.actor == actor { module.burning = false; module.fire_age = 0.0; }
    }
}

pub fn step(damage: &mut DamageState, geometry: &Geometry, dt: f64, effects: &mut Effects) {
    if !(dt > 0.0 && dt.is_finite()) { return; }
    let mut fires = BTreeMap::new();
    for module in &damage.modules {
        if module.attached && module.burning { fires.entry(scope(module)).or_insert(Vec::new()); }
    }
    if fires.is_empty() { return; }
    for (index, module) in damage.modules.iter().enumerate() {
        if module.attached {
            if let Some(parts) = fires.get_mut(&scope(module)) { parts.push(index); }
        }
    }
    let mut sources = Vec::new();
    for ((actor, outside), parts) in fires {
        let combustible = parts.iter().filter(|&&i| remaining(&damage.modules[i]) > 1e-8).count().max(1);
        let mut doses = Vec::new(); let mut active = Vec::new();
        let mut power = 0.0; let mut maximum: f64 = 1.15; let mut age: f64 = 0.0;
        for &i in &parts {
            let module = &mut damage.modules[i];
            if !module.burning { continue; }
            let fuel = remaining(module);
            if fuel <= 1e-8 { module.burning = false; module.fire_age = 0.0; continue; }
            module.fire_age += dt;
            let growth = development(module.fire_age);
            let limit: f64 = if module.kind == ComponentKind::Fuel && module.detonated && module.fuel_litres > 0.0 { 1.6 } else { 1.15 };
            let strength = (limit * (fuel / 80.0).sqrt()).clamp(0.08, limit) * growth;
            let before = module.burn_age;
            module.burn_age = (before + dt * growth).min(SOLID_SECONDS);
            if module.kind == ComponentKind::Fuel {
                module.fuel_litres = (module.fuel_litres - dt * growth * (module.capacity_litres / LIQUID_SECONDS).max(0.25)).max(0.0);
            }
            if module.kind.carrier() && module.cargo[3] > 0.0 {
                let capacity = module.kind.cargo_most(&CARGO[3], module.cargo_room);
                module.cargo[3] = (module.cargo[3] - dt * growth * (capacity / LIQUID_SECONDS).max(0.25)).max(0.0);
            }
            if module.kind == ComponentKind::Ammo {
                let spent = (module.burn_age * module.capacity_rounds as f64 / AMMO_SECONDS).floor()
                    - (before * module.capacity_rounds as f64 / AMMO_SECONDS).floor();
                module.rounds = module.rounds.saturating_sub(spent.max(0.0) as u32);
            }
            if module.usable() {
                doses.push((module.owner, point(module.pose.x, module.pose.y), module.max_health * strength * HEAT_PER_SECOND * dt));
            }
            if remaining(module) <= 1e-8 { module.burning = false; module.fire_age = 0.0; continue; }
            power += strength * strength; maximum = maximum.max(limit); age = age.max(module.fire_age);
            active.push((i, strength));
            sources.push((actor, outside.is_some(), module.owner, module.pose, module.width, module.height, strength));
        }
        // Rendering/audio still receive one bounded aggregate. A remote reserve is neither
        // consumed nor claimed by the effect until local heat has actually ignited it.
        if let Some(&(lead, _)) = active.iter().max_by(|a,b| a.1.total_cmp(&b.1).then_with(|| b.0.cmp(&a.0))) {
            let emitter = &damage.modules[lead];
            let radius = active.iter().map(|&(i, _)| {
                let m = &damage.modules[i];
                (m.pose.x-emitter.pose.x).hypot(m.pose.y-emitter.pose.y) + m.width * 0.35
            }).fold(0.15, f64::max);
            if effects.visual_events {
                effects.events.push(json!({"type":"burn","owner":emitter.owner,"x":emitter.pose.x,"y":emitter.pose.y,
                    "strength":power.sqrt().min(maximum),"radius":radius,
                    "spread":if outside.is_some(){0.0}else{involvement(age)*active.len() as f64/combustible as f64},"exterior":outside.is_some()}));
            }
        }
        for (owner, p, dose) in doses { damage.damage_module(owner, dose, p, effects); }
    }
    // Damage is also the accumulated thermal exposure: another piece must heat up
    // before it can ignite. No new per-part clock/checkpoint field is needed. The
    // same local falloff and material query serve both sides of the hull.
    let mut heated = BTreeMap::<u32, f64>::new();
    let mut barriers = Vec::new();
    for (actor, outside, owner, pose, width, height, strength) in sources {
        for target in &damage.modules {
            if target.actor != actor || target.owner == owner || !target.usable() || target.burning { continue; }
            // Crossing the hull keeps the short, dilute exposure of an open
            // source. Nearby tyres/tracks can warm; a remote reserve cannot.
            let open = outside || exterior(target);
            let reach = if open { EXTERIOR_REACH } else { INTERIOR_REACH };
            let transfer = if open { 0.35 } else { 1.25 };
            let distance = ((target.pose.x - pose.x).hypot(target.pose.y - pose.y)
                - width.hypot(height) * 0.5 - target.width.hypot(target.height) * 0.5).max(0.0);
            if distance >= reach { continue; }
            let start = point(pose.x, pose.y); let end = point(target.pose.x, target.pose.y);
            geometry.raycast_layers_into(start, end, &RayOptions { ignore_ids: &[owner, target.owner], only_actor: Some(actor), ..Default::default() }, &mut barriers);
            let falloff = (1.0 - distance / reach).powi(2);
            *heated.entry(target.owner).or_default() += target.max_health * strength * HEAT_PER_SECOND * transfer * falloff * transmission(damage, &barriers) * dt;
        }
    }
    for (owner, dose) in heated {
        let target = damage.module(owner).unwrap();
        let at = point(target.pose.x, target.pose.y);
        let dose = dose.min(target.max_health * HEAT_PER_SECOND * 1.6 * 1.25 * dt);
        damage.damage_module(owner, dose, at, effects);
        let target = damage.module_mut(owner).unwrap();
        if !target.burning && remaining(target) > 1e-8 && target.health < target.max_health * 0.45 {
            target.burning = true;
        }
    }
}

